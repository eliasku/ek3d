import assert from "node:assert/strict";
import { test } from "vite-plus/test";
import { SceneOptimizer } from "../src/addons/utils/SceneOptimizer";
import { BufferAttribute } from "../src/core/BufferAttribute";
import { BoxGeometry } from "../src/geometries/BoxGeometry";
import { MeshBasicMaterial } from "../src/materials/MeshBasicMaterial";
import { Color } from "../src/math/Color";
import { Matrix4 } from "../src/math/Matrix4";
import { BatchedMesh } from "../src/objects/BatchedMesh";
import { Group } from "../src/objects/Group";
import { Mesh } from "../src/objects/Mesh";
import { Scene } from "../src/scenes/Scene";

test("batching preserves local transforms, per-instance colors and distinct UV data", () => {
  const scene = new Scene();
  const parent = new Group();
  parent.position.set(5, 7, 9);
  scene.add(parent);
  const a = new Mesh(new BoxGeometry(), new MeshBasicMaterial({ color: 0xff0000 }));
  const b = new Mesh(new BoxGeometry(), new MeshBasicMaterial({ color: 0x00ff00 }));
  const sourceUV = b.geometry.attributes.uv;
  assert(sourceUV instanceof BufferAttribute);
  sourceUV.setXY(0, 0.25, 0.75);
  a.position.set(1, 2, 3);
  b.position.set(-1, 0, 2);
  a.castShadow = b.castShadow = true;
  parent.add(a, b);
  const result = new SceneOptimizer(scene).toBatchedMesh();
  assert.equal(result, scene);
  assert.equal(parent.children.length, 1);
  const batch = parent.children[0];
  assert(batch instanceof BatchedMesh);
  assert.equal(batch.castShadow, true);
  assert.equal(batch.instanceCount, 2);
  const matrix = new Matrix4();
  batch.getMatrixAt(0, matrix);
  assert.deepEqual(matrix.elements.slice(12, 15), [1, 2, 3]);
  batch.getMatrixAt(1, matrix);
  assert.deepEqual(matrix.elements.slice(12, 15), [-1, 0, 2]);
  const color = new Color();
  batch.getColorAt(0, color);
  assert.equal(color.getHex(), 0xff0000);
  batch.getColorAt(1, color);
  assert.equal(color.getHex(), 0x00ff00);
  const range = batch.getGeometryRangeAt(1);
  assert(range);
  const batchUV = batch.geometry.attributes.uv;
  assert(batchUV instanceof BufferAttribute);
  assert.equal(batchUV.getX(range.vertexStart), 0.25);
  assert.equal(batchUV.getY(range.vertexStart), 0.75);
});

test("batching leaves hidden-parent visibility and shared surviving resources intact", () => {
  const scene = new Scene();
  const geometry = new BoxGeometry();
  const material = new MeshBasicMaterial();
  let geometryDisposals = 0;
  let materialDisposals = 0;
  geometry.addEventListener("dispose", () => geometryDisposals++);
  material.addEventListener("dispose", () => materialDisposals++);
  const hidden = new Group();
  hidden.visible = false;
  const survivor = new Mesh(geometry, material);
  hidden.add(survivor);
  const visible = new Group();
  visible.add(new Mesh(geometry, material), new Mesh(geometry, material));
  scene.add(hidden, visible);
  new SceneOptimizer(scene).toBatchedMesh();
  assert.equal(hidden.visible, false);
  assert.equal(hidden.children[0], survivor);
  assert.equal(geometryDisposals, 0);
  assert.equal(materialDisposals, 0);
  assert(visible.children[0] instanceof BatchedMesh);
});
