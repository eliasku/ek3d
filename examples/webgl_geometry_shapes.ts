function addShape(
  shape: Shape,
  extrudeSettings: {
    depth: number;
    bevelEnabled: boolean;
    bevelSegments: number;
    steps: number;
    bevelSize: number;
    bevelThickness: number;
  },
  color: number,
  x: number,
  y: number,
  z: number,
  rx: number,
  ry: number,
  rz: number,
  s: number,
): void {
  // flat shape with texture
  // note: default UVs generated by ShapeGeometry are simply the x- and y-coordinates of the vertices

  let geometry: ShapeGeometry | ExtrudeGeometry = new ShapeGeometry(shape);

  let mesh = new Mesh(geometry, new MeshPhongMaterial({ side: Side.Double, map: texture }));
  mesh.position.set(x, y, z - 175);
  mesh.rotation.set(rx, ry, rz);
  mesh.scale.setScalar(s);
  group.add(mesh);

  // flat shape

  geometry = new ShapeGeometry(shape);

  mesh = new Mesh(geometry, new MeshPhongMaterial({ color: color, side: Side.Double }));
  mesh.position.set(x, y, z - 125);
  mesh.rotation.set(rx, ry, rz);
  mesh.scale.setScalar(s);
  group.add(mesh);

  // extruded shape

  geometry = new ExtrudeGeometry(shape, extrudeSettings);

  mesh = new Mesh(geometry, new MeshPhongMaterial({ color: color }));
  mesh.position.set(x, y, z - 75);
  mesh.rotation.set(rx, ry, rz);
  mesh.scale.setScalar(s);
  group.add(mesh);

  addLineShape(shape, color, x, y, z, rx, ry, rz, s);
}

function addLineShape(
  shape: Path,
  color: number,
  x: number,
  y: number,
  z: number,
  rx: number,
  ry: number,
  rz: number,
  s: number,
): void {
  // lines

  shape.autoClose = true;

  const points = shape.getPoints() as Vector2[];
  const spacedPoints = shape.getSpacedPoints(50) as Vector2[];

  const geometryPoints = new BufferGeometry().setFromPoints(points);
  const geometrySpacedPoints = new BufferGeometry().setFromPoints(spacedPoints);

  // solid line

  let line = new Line(geometryPoints, new LineBasicMaterial({ color: color }));
  line.position.set(x, y, z - 25);
  line.rotation.set(rx, ry, rz);
  line.scale.setScalar(s);
  group.add(line);

  // line from equidistance sampled points

  line = new Line(geometrySpacedPoints, new LineBasicMaterial({ color: color }));
  line.position.set(x, y, z + 25);
  line.rotation.set(rx, ry, rz);
  line.scale.setScalar(s);
  group.add(line);

  // vertices from real points

  let particles = new Points(geometryPoints, new PointsMaterial({ color: color, size: 4 }));
  particles.position.set(x, y, z + 75);
  particles.rotation.set(rx, ry, rz);
  particles.scale.setScalar(s);
  group.add(particles);

  // equidistance sampled points

  particles = new Points(geometrySpacedPoints, new PointsMaterial({ color: color, size: 4 }));
  particles.position.set(x, y, z + 125);
  particles.rotation.set(rx, ry, rz);
  particles.scale.setScalar(s);
  group.add(particles);
}

