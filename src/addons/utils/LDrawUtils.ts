import { mergeGeometries } from "./BufferGeometryUtils";
import { BufferAttribute } from "../../core/BufferAttribute";
import { BufferGeometry } from "../../core/BufferGeometry";
import type { LineSegments } from "../../objects/LineSegments";
import { LineSegments as LineSegmentsImpl } from "../../objects/LineSegments";
import { Matrix3 } from "../../math/Matrix3";
import { Mesh as MeshImpl } from "../../objects/Mesh";
import type { Group } from "../../objects/Group";
import { Group as GroupImpl } from "../../objects/Group";

/**
 * Utility class for LDraw models.
 *
 * ```ts
 * model = LDrawUtils.mergeObject( model );
 * ```
 *
 */
export class LDrawUtils {
  /**
   * Merges geometries in the given object by materials and returns a new group object.
   * Use on not indexed geometries. The object buffers reference the old object ones.
   * Special treatment is done to the conditional lines generated by {@link LDrawLoader}.
   *
   * @param object - The object to merge.
   * @returns The merged object.
   */
  static mergeObject(object: Group): Group {
    // Extracts a group from a geometry as a new geometry (with attribute buffers referencing original buffers)

    function extractGroup(
      geometry: BufferGeometry,
      group: { count: number; start: number },
      elementSize: number,
      isConditionalLine: boolean,
    ): BufferGeometry {
      const newGeometry = new BufferGeometry();

      const originalPositions = (geometry.getAttribute("position") as BufferAttribute).array as Float32Array;
      const originalNormalsAttr =
        elementSize === 3 ? (geometry.getAttribute("normal") as BufferAttribute | undefined) : undefined;
      const originalNormals = originalNormalsAttr !== undefined ? (originalNormalsAttr.array as Float32Array) : null;

      const numVertsGroup = Math.min(group.count, Math.floor(originalPositions.length / 3) - group.start);
      const vertStart = group.start * 3;
      const vertEnd = (group.start + numVertsGroup) * 3;

      const positions = originalPositions.subarray(vertStart, vertEnd);
      const normals = originalNormals !== null ? originalNormals.subarray(vertStart, vertEnd) : null;

      newGeometry.setAttribute("position", new BufferAttribute(positions as never, 3));
      if (normals !== null) newGeometry.setAttribute("normal", new BufferAttribute(normals as never, 3));

      if (isConditionalLine) {
        const controlArray0 = ((geometry.getAttribute("control0") as BufferAttribute).array as Float32Array).subarray(
          vertStart,
          vertEnd,
        );
        const controlArray1 = ((geometry.getAttribute("control1") as BufferAttribute).array as Float32Array).subarray(
          vertStart,
          vertEnd,
        );
        const directionArray = ((geometry.getAttribute("direction") as BufferAttribute).array as Float32Array).subarray(
          vertStart,
          vertEnd,
        );

        newGeometry.setAttribute("control0", new BufferAttribute(controlArray0 as never, 3, false));
        newGeometry.setAttribute("control1", new BufferAttribute(controlArray1 as never, 3, false));
        newGeometry.setAttribute("direction", new BufferAttribute(directionArray as never, 3, false));
      }

      return newGeometry;
    }

    type GeometryBucket = { mat: unknown; arr: BufferGeometry[] };

    function addGeometry(mat: unknown, geometry: BufferGeometry, geometries: Record<string, GeometryBucket>): void {
      const geoms = geometries[(mat as { uuid: string }).uuid];
      if (!geoms) {
        geometries[(mat as { uuid: string }).uuid] = {
          mat: mat,
          arr: [geometry],
        };
      } else {
        geoms.arr.push(geometry);
      }
    }

    function permuteAttribute(attribute: BufferAttribute | undefined, elemSize: number): void {
      // Permutes first two vertices of each attribute element

      if (!attribute) return;

      const verts = attribute.array as Float32Array;
      const numVerts = Math.floor(verts.length / 3);
      let offset = 0;
      for (let i = 0; i < numVerts; i++) {
        const x = verts[offset];
        const y = verts[offset + 1];
        const z = verts[offset + 2];

        verts[offset] = verts[offset + 3];
        verts[offset + 1] = verts[offset + 4];
        verts[offset + 2] = verts[offset + 5];

        verts[offset + 3] = x;
        verts[offset + 4] = y;
        verts[offset + 5] = z;

        offset += elemSize * 3;
      }
    }

    // Traverse the object hierarchy collecting geometries and transforming them to world space

    const meshGeometries: Record<string, GeometryBucket> = {};
    const linesGeometries: Record<string, GeometryBucket> = {};
    const condLinesGeometries: Record<string, GeometryBucket> = {};

    object.updateMatrixWorld(true);
    const normalMatrix = new Matrix3();

    object.traverse((c) => {
      const holder = c as unknown as {
        isMesh?: boolean;
        isLineSegments?: boolean;
        isConditionalLine?: boolean;
        matrixWorld: import("../../math/Matrix4").Matrix4;
        geometry: BufferGeometry;
        material?: unknown;
      };

      if (holder.isMesh || holder.isLineSegments) {
        const elemSize = holder.isMesh ? 3 : 2;

        const geometry = holder.geometry.clone();
        const matrixIsInverted = holder.matrixWorld.determinant() < 0;
        if (matrixIsInverted) {
          permuteAttribute(geometry.getAttribute("position") as BufferAttribute, elemSize);
          permuteAttribute(geometry.getAttribute("normal") as BufferAttribute, elemSize);
        }

        geometry.applyMatrix4(holder.matrixWorld);

        if (holder.isConditionalLine) {
          (geometry.getAttribute("control0") as BufferAttribute).applyMatrix4(holder.matrixWorld);
          (geometry.getAttribute("control1") as BufferAttribute).applyMatrix4(holder.matrixWorld);
          normalMatrix.getNormalMatrix(holder.matrixWorld);
          (geometry.getAttribute("direction") as BufferAttribute).applyNormalMatrix(normalMatrix);
        }

        const geometries = holder.isMesh
          ? meshGeometries
          : holder.isConditionalLine
            ? condLinesGeometries
            : linesGeometries;

        if (Array.isArray(holder.material)) {
          for (const group of geometry.groups) {
            const mat = (holder.material as unknown[])[group.materialIndex!];
            const newGeometry = extractGroup(geometry, group, elemSize, holder.isConditionalLine === true);
            addGeometry(mat, newGeometry, geometries);
          }
        } else {
          addGeometry(holder.material, geometry, geometries);
        }
      }
    });

    // Create object with merged geometries

    const mergedObject = new GroupImpl();

    const meshMaterialsIds = Object.keys(meshGeometries);
    for (const meshMaterialsId of meshMaterialsIds) {
      const meshGeometry = meshGeometries[meshMaterialsId]!;
      const mergedGeometry = mergeGeometries(meshGeometry.arr as never);
      mergedObject.add(new MeshImpl(mergedGeometry as never, meshGeometry.mat as never));
    }

    const linesMaterialsIds = Object.keys(linesGeometries);
    for (const linesMaterialsId of linesMaterialsIds) {
      const lineGeometry = linesGeometries[linesMaterialsId]!;
      const mergedGeometry = mergeGeometries(lineGeometry.arr as never);
      mergedObject.add(new LineSegmentsImpl(mergedGeometry as never, lineGeometry.mat as never));
    }

    const condLinesMaterialsIds = Object.keys(condLinesGeometries);
    for (const condLinesMaterialsId of condLinesMaterialsIds) {
      const condLineGeometry = condLinesGeometries[condLinesMaterialsId]!;
      const mergedGeometry = mergeGeometries(condLineGeometry.arr as never);
      const condLines = new LineSegmentsImpl(mergedGeometry as never, condLineGeometry.mat as never) as LineSegments & {
        isConditionalLine: boolean;
      };
      condLines.isConditionalLine = true;
      mergedObject.add(condLines);
    }

    (mergedObject.userData as { constructionStep: number; numConstructionSteps: number }).constructionStep = 0;
    (mergedObject.userData as { constructionStep: number; numConstructionSteps: number }).numConstructionSteps = 1;

    return mergedObject;
  }
}
