import type { LoadingManager } from "../../loaders/LoadingManager";
import { FileLoader } from "../../loaders/FileLoader";
import { Loader } from "../../loaders/Loader";
import { ShapePath } from "../../extras/core/ShapePath";
import type { Shape } from "../../extras/core/Shape";
import { error } from "../../utils";

/**
 * Char direction of generated text shapes.
 */
export type FontDirection = "ltr" | "rtl" | "tb";

/**
 * A single glyph of a typeface JSON font.
 */
export interface Glyph {
  x_min: number;
  x_max: number;
  /** Horizontal advance in font units. */
  ha: number;
  /** Outline commands (`m`, `l`, `q`, `b`) in font units. Absent for whitespace-only glyphs. */
  o?: string;
  /** Parsed `o` commands. Populated by {@link Font.generateShapes}. */
  _cachedOutline?: string[];
}

/**
 * Font metadata embedded in a typeface JSON file.
 */
export interface FontOriginalInformation {
  postscript_name: string;
  version_string: string;
  vendor_url: string;
  full_font_name: string;
  font_family_name: string;
  copyright: string;
  description: string;
  trademark: string;
  designer: string;
  designer_url: string;
  unique_font_identifier: string;
  license_url: string;
  license_description: string;
  manufacturer_name: string;
  font_sub_family_name: string;
}

/**
 * The typeface JSON data consumed by {@link Font}, as generated by
 * [facetype.js](https://gero3.github.io/facetype.js/).
 */
export interface FontData {
  glyphs: Record<string, Glyph | undefined>;
  familyName: string;
  ascender: number;
  descender: number;
  underlinePosition: number;
  underlineThickness: number;
  boundingBox: { xMin: number; xMax: number; yMin: number; yMax: number };
  resolution: number;
  lineHeight?: number;
  cssFontWeight?: string;
  cssFontStyle?: string;
  original_font_information?: FontOriginalInformation;
}

/**
 * A loader for typeface JSON fonts.
 *
 * ```typescript
 * import { FontLoader } from 'ek3d/addons/loaders/FontLoader';
 *
 * const loader = new FontLoader();
 * const url = new URL( './helvetiker_regular.typeface.json', import.meta.url ).href;
 * const font = await loader.loadAsync( url );
 * ```
 */
export class FontLoader extends Loader<Font> {
  /**
   * Constructs a new font loader.
   *
   * @param manager - The loading manager.
   */
  constructor(manager?: LoadingManager) {
    super(manager);
  }
  /**
   * Starts loading from the given URL and passes the loaded font to the `onLoad()` callback.
   *
   * @param url - The path/URL of the file to be loaded. This can also be a data URI.
   * @param onLoad - Executed when the loading process has been finished.
   * @param onProgress - Executed while the loading is in progress.
   * @param onError - Executed when errors occur.
   */
  load(
    url: string,
    onLoad?: (value: Font) => void,
    onProgress?: (event: ProgressEvent) => void,
    onError?: (error: unknown) => void,
  ): void {
    const loader = new FileLoader(this.manager);
    loader.setPriority(this.priority);
    loader.setCache(this.cache);
    loader.setPath(this.path);
    loader.setRequestHeader(this.requestHeader);
    loader.setWithCredentials(this.withCredentials);
    loader.load(
      url,
      (text) => {
        try {
          if (typeof text !== "string") throw new Error("FontLoader: Expected a JSON text response.");
          const font = this.parse(JSON.parse(text) as FontData);
          if (onLoad !== undefined) onLoad(font);
        } catch (e) {
          if (onError !== undefined) onError(e);
          else error(e);
          this.manager.itemError(url);
        }
      },
      onProgress,
      onError,
    );
  }
  /**
   * Parses the given font data and returns the resulting font.
   *
   * @param json - The raw font data as a JSON object.
   * @return The font.
   */
  parse(json: FontData): Font {
    return new Font(json);
  }
}

/**
 * Represents a typeface JSON font.
 *
 * ```typescript
 * import { FontLoader } from 'ek3d/addons/loaders/FontLoader';
 *
 * const font = await new FontLoader().loadAsync( './optimer_bold.typeface.json' );
 * const shapes = font.generateShapes( 'Text', 70, 'rtl' );
 * ```
 */
export class Font {
  isFont: boolean;
  type: string;
  data: FontData;

  /**
   * Constructs a new font.
   *
   * @param data - The font data as JSON.
   */
  constructor(data: FontData) {
    this.isFont = true;
    this.type = "Font";
    this.data = data;
  }
  /**
   * Generates shapes from the given text and size. The result can be passed to
   * {@link ExtrudeGeometry} to generate the actual geometry data.
   *
   * @param text - The text.
   * @param size - The text size.
   * @param direction - Char direction.
   * @return An array of shapes representing the text.
   */
  generateShapes(text: string, size: number = 100, direction: FontDirection = "ltr"): Shape[] {
    const shapes: Shape[] = [];
    const paths = createPaths(text, size, this.data, direction);
    for (let p = 0, pl = paths.length; p < pl; p++) {
      shapes.push(...paths[p].toShapes());
    }
    return shapes;
  }
}

function createPaths(text: string, size: number, data: FontData, direction: FontDirection): ShapePath[] {
  const chars = Array.from(text);
  const scale = size / data.resolution;
  const lineHeight = (data.boundingBox.yMax - data.boundingBox.yMin + data.underlineThickness) * scale;
  const paths: ShapePath[] = [];
  let offsetX = 0;
  let offsetY = 0;
  if (direction === "rtl" || direction === "tb") chars.reverse();
  for (let i = 0; i < chars.length; i++) {
    const char = chars[i];
    if (char === "\n") {
      offsetX = 0;
      offsetY -= lineHeight;
    } else {
      const ret = createPath(char, scale, offsetX, offsetY, data);
      if (direction === "tb") {
        offsetX = 0;
        offsetY += data.ascender * scale;
      } else {
        offsetX += ret.offsetX;
      }
      paths.push(ret.path);
    }
  }
  return paths;
}

function createPath(
  char: string,
  scale: number,
  offsetX: number,
  offsetY: number,
  data: FontData,
): { offsetX: number; path: ShapePath } {
  const glyph = data.glyphs[char] ?? data.glyphs["?"];
  if (glyph === undefined) {
    throw new Error(`FontLoader: character "${char}" does not exist in font family ${data.familyName}.`);
  }
  const path = new ShapePath();
  if (glyph.o !== undefined) {
    const outline = glyph._cachedOutline ?? (glyph._cachedOutline = glyph.o.split(" "));
    for (let i = 0, l = outline.length; i < l;) {
      const action = outline[i++];
      switch (action) {
        case "m": {
          const x = Number(outline[i++]) * scale + offsetX;
          const y = Number(outline[i++]) * scale + offsetY;
          path.moveTo(x, y);
          break;
        }
        case "l": {
          const x = Number(outline[i++]) * scale + offsetX;
          const y = Number(outline[i++]) * scale + offsetY;
          path.lineTo(x, y);
          break;
        }
        case "q": {
          const cpx = Number(outline[i++]) * scale + offsetX;
          const cpy = Number(outline[i++]) * scale + offsetY;
          const cpx1 = Number(outline[i++]) * scale + offsetX;
          const cpy1 = Number(outline[i++]) * scale + offsetY;
          path.quadraticCurveTo(cpx1, cpy1, cpx, cpy);
          break;
        }
        case "b": {
          const cpx = Number(outline[i++]) * scale + offsetX;
          const cpy = Number(outline[i++]) * scale + offsetY;
          const cpx1 = Number(outline[i++]) * scale + offsetX;
          const cpy1 = Number(outline[i++]) * scale + offsetY;
          const cpx2 = Number(outline[i++]) * scale + offsetX;
          const cpy2 = Number(outline[i++]) * scale + offsetY;
          path.bezierCurveTo(cpx1, cpy1, cpx2, cpy2, cpx, cpy);
          break;
        }
      }
    }
  }
  return { offsetX: glyph.ha * scale, path };
}
